package HerenciaYPolimorfismo.ejercicios.calculadora;

public class CalculadoraBasica {
	public CalculadoraBasica (){
	}
	public int Sumar(int par1, int par2) {
		return par1+par2;
	}
	public int Restar(int par1, int par2) {
		return par1-par2;
	}
	public int Multiplicar(int par1, int par2) {
		return par1*par2;
	}
	public float Dividir(int par1, int par2) {
		return par1/par2;
	}

}
